export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, fr };

export function detectLang(doc: Document): Lang {
  const lang = doc.querySelector('meta[name="ogame-language"]')?.getAttribute('content');
  return lang === 'fr' ? 'fr' : 'en';
}

export function createT(lang: Lang) {
  return (key: MessageKey, vars?: Record<string, string>): string => {
    let text = MESSAGES[lang][key];
    for (const [k, v] of Object.entries(vars ?? {})) text = text.replaceAll(`{${k}}`, () => v);
    return text;
  };
}

export type T = ReturnType<typeof createT>;

export function errorKey(error: ApiError): MessageKey {
  return `error.${error}`;
}
